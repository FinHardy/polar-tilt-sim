"""Which way each simulated structure is polarised along the measured detector axis.

Result (lab x = pattern array axis 0, the axis the boxes measure):
    PTO       +38.2 uC/cm2   (+x)
    BTO       -17.9 uC/cm2   (-x)   reversed relative to PTO
    boracite   -0.71 uC/cm2  (-x)   point-charge estimate, NOT used (see below)

Method: P = sum_i q_i (r_i - r'_pi(i)) / 2V with formal charges, where r' is the
P-reversed domain generated by a symmetry operation of the parent phase that the polar
phase lost (m_z for the P4mm perovskites; a 2-fold about cubic x or y, i.e. along a+b or
a-b, for Pca2_1 boracite, whose F-43c parent is itself acentric, so an inversion-centre
reference would be wrong). pi maps each atom to its nearest same-species partner after
the best overlay translation. Both boracite operations agree. The crystal -> lab
rotation is the one the sim scripts apply (zone axis -> z, then the z rotation).

Boracite override: the point-charge sign is set only by the formal +3 charge on the 28 B
ions; the Cu and Cl contributions both point +x. The established mechanism (Schmid;
Thornley & Nelmes; McQuaid et al., Nat. Commun. 2017) and the companion DFT paper
(arXiv 2510.00693) attribute P to the relative Cu/Cl shift, i.e. +x, along the Cu
displacement. So boracite is taken as polarised like PTO (P_REVERSED False). No Berry-phase
value has been published; replace this if one becomes available.

Run with the sim-cbed-311 env (needs ase):  python polarisation_direction.py
"""
import numpy as np

# Simulated P reversed relative to PTO along lab x. Aligning a reversed dataset to PTO is
# the exact mirror through the plane perpendicular to P: y(t) -> -y(-t).
P_REVERSED = {"PTO": False, "BTO": True, "Boracite": False}   # boracite: Cu/Cl mechanism, see docstring

Q = dict(Pb=2, Ba=2, Ti=4, O=-2, Cu=2, B=3, Cl=-1)
CIFS = {"PTO": "cifs/pbtio3_polarised_2.cif", "BTO": "cifs/batio3_polarised.cif",
        "Boracite": "cifs/cu2-ortho-sym.cif"}


def domain_disp(atoms, op):
    """Per-atom polar displacement (A, crystal cartesian frame): half the difference
    between each atom and its partner in the domain reversed by `op`. atoms.positions -
    domain_disp is the non-polar reference (the midpoint of the two domains)."""
    cell = atoms.cell.array; inv = np.linalg.inv(cell)
    r = atoms.positions; sym = np.array(atoms.get_chemical_symbols())

    def mic(d):
        f = d @ inv
        return (f - np.round(f)) @ cell

    rr = r @ op.T
    rare = np.flatnonzero(sym == min(set(sym), key=lambda s: (sym == s).sum()))
    best = (np.inf, None)
    for i in rare:                         # overlay translations from the rarest species
        for j in rare:
            t = mic(r[i] - rr[j])
            d_all, cost = np.zeros_like(r), 0.0
            for s in set(sym):
                idx = np.flatnonzero(sym == s)
                d = mic(r[idx][:, None] - (rr[idx] + t)[None])
                n = np.linalg.norm(d, axis=2); k = n.argmin(1)
                if len(set(k)) < len(k):   # not a bijection
                    cost = np.inf; break
                cost += (n[np.arange(len(idx)), k]**2).sum()
                d_all[idx] = d[np.arange(len(idx)), k]
            if cost < best[0]:
                best = (cost, d_all)
    return best[1] / 2


def domain_P(atoms, op):
    """Nominal P (uC/cm2, crystal cartesian frame) from the domain reversed by `op`."""
    q = np.array([Q[s] for s in atoms.get_chemical_symbols()])
    return (q[:, None] * domain_disp(atoms, op)).sum(0) / atoms.get_volume() * 1602.177


def boracite_op(atoms):
    """The lost parent 2-fold about cubic x (along a+b) that reverses boracite's P."""
    A, B = atoms.cell.array[:2]
    u = (A + B) / np.linalg.norm(A + B)
    return 2 * np.outer(u, u) - np.eye(3)


def lab_rotation(zone, zrot):
    """Linear part of the sim scripts' orientation: zone axis -> z, then rotate about z."""
    from ase import Atoms
    p = Atoms("H4", positions=np.vstack([np.zeros(3), np.eye(3)]))
    z = np.array([0., 0., 1.]); v = np.array(zone, float); v /= np.linalg.norm(v)
    ax = np.cross(v, z)
    if np.linalg.norm(ax) > 1e-6:
        p.rotate(np.degrees(np.arccos(v @ z)), ax / np.linalg.norm(ax))
    if zrot:
        p.rotate(zrot, "z")
    return (p.positions[1:] - p.positions[0]).T


def lab_P():
    from ase.io import read
    out = {}
    for name in ("PTO", "BTO"):
        P = domain_P(read(CIFS[name]), np.diag([1, 1, -1.]))
        out[name] = lab_rotation([1, 0, 0], 0) @ P
    a = read(CIFS["Boracite"]); A, B = a.cell.array[:2]
    Ps = []
    for u in (A + B, A - B):
        u = u / np.linalg.norm(u)
        Ps.append(lab_rotation([1, 1, 0], -45) @ domain_P(a, 2*np.outer(u, u) - np.eye(3)))
    assert np.allclose(Ps[0], Ps[1], atol=1e-6), Ps
    out["Boracite"] = Ps[0]
    return out


if __name__ == "__main__":
    P = lab_P()
    for k, v in P.items():
        print(f"{k:9s} P_lab = {np.round(v, 2)} uC/cm2")
    assert np.isclose(P["PTO"][0], 38.19, atol=0.05) and np.isclose(P["BTO"][0], -17.91, atol=0.05)
    assert all(abs(v[1]) < 1e-6 and abs(v[2]) < 1e-6 for v in P.values())   # all on lab x
    ref = np.sign(P["PTO"][0])
    pc = {k: bool(np.sign(v[0]) != ref) for k, v in P.items()}
    assert all(pc[k] == P_REVERSED[k] for k in ("PTO", "BTO")), pc
    assert pc["Boracite"] != P_REVERSED["Boracite"]   # deliberate override, see docstring
    print("P_REVERSED consistent with the structures (boracite: Cu/Cl mechanism, not point charges)")
